import { writeFileSync } from "node:fs";
import { it } from "vitest";
import { openPage } from "./harness";

// Regenerates core/text/inter-advances.ts from the Inter fixture: `GENERATE_ADVANCES=1 npm run test:browser`.
(process.env.GENERATE_ADVANCES ? it : it.skip)("generate Inter advance widths", async () => {
  const s = await openPage({ font: "inter" });
  const table = await s.page.evaluate(() => {
    const ctx = document.createElement("canvas").getContext("2d")!;
    const out: Record<string, number[]> = {};
    for (const weight of ["400", "500", "600", "700"]) {
      ctx.font = `normal ${weight} 1000px Inter, sans-serif`;
      const row: number[] = [];
      for (let code = 32; code <= 126; code += 1) row.push(Math.round(ctx.measureText(String.fromCharCode(code)).width));
      out[weight] = row;
    }
    return out;
  });
  const rows = Object.entries(table)
    .map(([w, row]) => `  ${w}: [${row.join(", ")}],`)
    .join("\n");
  writeFileSync(
    new URL("../../core/text/inter-advances.ts", import.meta.url),
    `// Generated by tests/browser/calib.browser.test.ts from Inter (SIL OFL 1.1). Do not edit by hand.
// Advance widths in 1/1000 em for ASCII 32-126, per weight. Kerning is not included (it only narrows text).
export const INTER_ADVANCES: Record<number, number[]> = {
${rows}
};
`,
  );
  await s.close();
});
