// Vendors a fixed set of lucide icons (ISC) as plain SVG path strings into core/icons/glyphs.ts.
// Run: node scripts/generate-icon-glyphs.mjs   (reads node_modules/lucide-react, no runtime import of it)
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const NAMES = `database server cloud globe cpu hard-drive memory-stick network router shield shield-check key-round lock
user users smartphone monitor layout-dashboard bell settings git-branch workflow container boxes box layers zap mail
message-square radio-tower waypoints brain bot wrench book-open activity microchip circuit-board plug wifi bluetooth battery
thermometer radio usb cable brick-wall archive webhook scale split repeat rotate-cw git-fork external-link rows-3 gauge
signpost cloud-cog file-code rocket terminal sensors hexagon circle-help package gitlab`.split(/\s+/);

// Glyphs only the catalog (core/icons/catalog.json) names go to glyphs-extra.ts, which loads on demand with the
// logos (see core/icons/library.ts); the curated ones above stay in glyphs.ts so a board always draws them.
const catalog = JSON.parse(readFileSync("core/icons/catalog.json", "utf8"));
const CORE = new Set(NAMES);
const EXTRA = [];
for (const entries of Object.values(catalog)) for (const entry of entries) if (!CORE.has(entry.split("|")[0])) EXTRA.push(entry.split("|")[0]);
NAMES.push(...EXTRA);

const attr = (a, k, d = 0) => Number(a[k] ?? d);
const toPath = (tag, a) => {
  switch (tag) {
    case "path": return a.d;
    case "line": return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
    case "polyline": return `M${a.points.trim().split(/\s+/).join("L")}`;
    case "polygon": return `M${a.points.trim().split(/\s+/).join("L")}Z`;
    case "circle": { const [cx, cy, r] = [attr(a, "cx"), attr(a, "cy"), attr(a, "r")]; return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`; }
    case "ellipse": { const [cx, cy, rx, ry] = [attr(a, "cx"), attr(a, "cy"), attr(a, "rx"), attr(a, "ry")]; return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`; }
    case "rect": {
      const [x, y, w, h] = [attr(a, "x"), attr(a, "y"), attr(a, "width"), attr(a, "height")];
      const r = Math.min(attr(a, "rx", attr(a, "ry")), w / 2, h / 2);
      return r ? `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z` : `M${x} ${y}h${w}v${h}h${-w}Z`;
    }
    default: throw new Error(`unsupported tag ${tag}`);
  }
};

const out = {}; const missing = [];
for (const n of [...new Set(NAMES)]) {
  const f = `node_modules/lucide-react/dist/esm/icons/${n}.js`;
  if (!existsSync(f)) { missing.push(n); continue; }
  const src = readFileSync(f, "utf8");
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\nconst /);
  if (!m) { missing.push(n); continue; }
  const nodes = Function(`return ${m[1]}`)();
  out[n] = nodes.map(([tag, a]) => toPath(tag, a)); // one string per shape: they must not be concatenated (relative `m`)
}
const header = (file, what) => `// GENERATED by scripts/generate-icon-glyphs.mjs from lucide (ISC License, https://lucide.dev). Do not edit.
// ${what}
// 24x24 viewBox, stroked (width 2, round caps/joins). Each entry is a list of separate SVG paths.
`;
const fmt = (names) => names.filter((n) => out[n]).map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(out[k])},`).join("\n");
writeFileSync("core/icons/glyphs.ts", `${header("glyphs", "The curated icons: always loaded.")}export const GLYPHS: Record<string, string[]> = {\n${fmt([...CORE])}\n};\n`);
writeFileSync("core/icons/glyphs-extra.ts", `${header("glyphs-extra", "The catalog icons: loaded on demand.")}export const GLYPHS_EXTRA: Record<string, string[]> = {\n${fmt([...new Set(EXTRA)])}\n};\n`);
console.log(`wrote ${Object.keys(out).length} glyphs (${CORE.size} core); missing: ${missing.join(", ") || "none"}`);
