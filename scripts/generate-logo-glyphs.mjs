// Vendors a curated set of brand marks from Simple Icons (CC0 data) into core/icons/logos.ts.
// Run: npm i --no-save simple-icons && node scripts/generate-logo-glyphs.mjs   (no runtime dependency on it)
// Simple Icons has removed some marks at their owners' request (Amazon Web Services, Microsoft Azure, OpenAI,
// Slack, ...); those cannot be vendored here, and users add them through custom SVG icons instead.
import { writeFileSync } from "node:fs";
import * as si from "simple-icons";

const SLUGS = `googlecloud docker kubernetes terraform ansible jenkins github gitlab githubactions nginx kong istio vault
postgresql mysql mariadb sqlite mongodb redis apachekafka rabbitmq apachecassandra elasticsearch snowflake databricks apachespark
nodedotjs react nextdotjs typescript python go rust graphql linux ubuntu
cloudflare vercel supabase firebase stripe clerk convex anthropic
grafana prometheus datadog sentry figma notion postman`.split(/\s+/);

const all = Object.values(si).filter((x) => x && x.slug);
const bySlug = new Map(all.map((x) => [x.slug, x]));

const lin = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const lum = (hex) => {
  const [r, g, b] = [0, 2, 4].map((i) => lin(Number.parseInt(hex.slice(i, i + 2), 16) / 255));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
// Brand colours are drawn on a white tile; a pale one (yellow, light grey) would vanish, so it falls back to slate.
const readable = (hex) => (1.05 / (lum(hex) + 0.05) >= 3 ? `#${hex.toLowerCase()}` : "#1f2937");

const out = [];
const missing = [];
for (const slug of SLUGS) {
  const icon = bySlug.get(slug);
  if (!icon) { missing.push(slug); continue; }
  out.push({ slug, title: icon.title, path: icon.path, color: readable(icon.hex) });
}
out.sort((a, b) => a.title.localeCompare(b.title));

const body = out.map((l) => `  ${JSON.stringify(l)},`).join("\n");
writeFileSync(
  "core/icons/logos.ts",
  `// GENERATED by scripts/generate-logo-glyphs.mjs from Simple Icons (data: CC0-1.0, https://simpleicons.org). Do not edit.
// Each mark is a trademark of its owner, shown only to name the technology in a diagram (nominative use).
// Marks the owners asked Simple Icons to remove (AWS, Azure, ...) are not included; use a custom SVG icon for those.
// 24x24 viewBox, filled single path.
export interface Logo {
  slug: string;
  title: string;
  path: string;
  /** Brand colour, or slate when the brand colour is too pale for a white tile. */
  color: string;
}

export const LOGOS: Logo[] = [
${body}
];
`,
);
console.log(`wrote ${out.length} logos; missing: ${missing.join(", ") || "none"}`);
